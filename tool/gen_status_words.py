#!/usr/bin/env python3
"""Writes the contract status words (contracts/contract.json#statusWords)
into lib/l10n/app_{en,fr,sv}.arb and lib/core/contracts/status_words.g.dart.

Run after syncing the contract:  python3 tool/gen_status_words.py
Then: flutter gen-l10n. test/l10n/status_words_contract_test.dart fails
when an ARB word differs from the contract.
"""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
PACKAGE = 'movera_rider'
FAMILIES = ['tripStatus', 'paymentStatus', 'feeStatus', 'ticketStatus', 'ratingStatus']

contract = json.loads((root / 'contracts/contract.json').read_text(encoding='utf-8'))
families = contract['statusWords']['families']


def camel(s):
    return ''.join(p[:1].upper() + p[1:] for p in re.split(r'[_\W]+', s) if p)


def key(family, code):
    return 'sw' + camel(family) + camel(code)


SW = re.compile(r'^  "@?sw[A-Z][A-Za-z0-9]*": ')

for lang in ('en', 'fr', 'sv'):
    path = root / f'lib/l10n/app_{lang}.arb'
    lines = [l for l in path.read_text(encoding='utf-8').rstrip().split('\n') if not SW.match(l)]
    assert lines[-1] == '}', path
    body = lines[:-1]
    body[-1] = body[-1].rstrip(',')
    add = []
    for f in FAMILIES:
        for code, words in families[f].items():
            add.append(f'  {json.dumps(key(f, code))}: {json.dumps(words[lang], ensure_ascii=False)}')
            if lang == 'en':
                desc = {'description': f'Contract status word statusWords.families.{f}.{code} (tool/gen_status_words.py).'}
                add.append(f'  {json.dumps("@" + key(f, code))}: {json.dumps(desc)}')
    body[-1] += ','
    text = '\n'.join(body + [',\n'.join(add), '}']) + '\n'
    json.loads(text)
    path.write_text(text, encoding='utf-8')

out = [
    '// GENERATED by tool/gen_status_words.py from contracts/contract.json#statusWords.',
    '// Do not edit by hand.',
    f"import 'package:{PACKAGE}/l10n/generated/app_localizations.dart';",
    '',
    '/// The status families this app shows (contract statusWords.families).',
    'const statusWordFamilies = <String, List<String>>{',
]
for f in FAMILIES:
    out.append(f"  '{f}': [{', '.join(repr(c).replace(chr(34), chr(39)) for c in families[f])}],")
out += [
    '};',
    '',
    '/// The contract word for [code] of [family] in [l]\'s language, or null',
    '/// when the contract has no such code.',
    'String? statusWord(AppLocalizations l, String family, String code) {',
    '  switch (family) {',
]
for f in FAMILIES:
    out.append(f"    case '{f}':")
    out.append('      switch (code) {')
    for code in families[f]:
        out.append(f"        case '{code}':")
        out.append(f'          return l.{key(f, code)};')
    out.append('      }')
    out.append('      return null;')
out += ['  }', '  return null;', '}', '']
dart = root / 'lib/core/contracts/status_words.g.dart'
dart.write_text('\n'.join(out), encoding='utf-8')
print(f'wrote {sum(len(families[f]) for f in FAMILIES)} status words for {len(FAMILIES)} families')
