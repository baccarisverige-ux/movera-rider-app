#!/usr/bin/env python3
"""Writes test/l10n/all_messages.g.dart from lib/l10n/app_en.arb.

Run after adding or removing a message:  python3 tool/gen_l10n_messages.py

The generated file lists every message of gen-l10n's AppLocalizations, so
the parity test reads each language through gen-l10n's own output. Its
_Exhaustive class implements AppLocalizations: a message missing from the
list does not compile, and one that no longer exists is an analyzer error
(override_on_non_overriding_member).
"""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
arb = json.loads((root / 'lib/l10n/app_en.arb').read_text(encoding='utf-8'))
keys = [k for k in arb if not k.startswith('@')]


def params(key):
    meta = arb.get('@' + key, {})
    return list(meta.get('placeholders', {}).items())


def sample(name, spec):
    # Distinct, easy to find values: a placeholder must survive translation.
    if spec.get('type') in ('int', 'num', 'double'):
        return '3'
    return f"'<{name}>'"


def dart_type(spec):
    return {'int': 'int', 'num': 'num', 'double': 'double'}.get(spec.get('type'), 'String')


lines = [
    '// GENERATED by tool/gen_l10n_messages.py from lib/l10n/app_en.arb.',
    '// Do not edit by hand; run the tool after changing the template ARB.',
    '// ignore_for_file: type=lint',
    "import 'package:movera_rider/l10n/l10n.dart';",
    '',
    '/// Every message of [l], by key. Placeholders get `<name>` (strings)',
    '/// or 3 (counts), so a test can check they survive translation.',
    'Map<String, String> allMessages(AppLocalizations l) => {',
]
for k in keys:
    ps = params(k)
    if ps:
        args = ', '.join(sample(n, s) for n, s in ps)
        lines.append(f"  '{k}': l.{k}({args}),")
    else:
        lines.append(f"  '{k}': l.{k},")
lines += ['};', '',
          '/// The placeholders of each message, by key.',
          'const messagePlaceholders = <String, List<String>>{']
for k in keys:
    ps = params(k)
    if ps:
        names = ', '.join(f"'{n}'" for n, s in ps if dart_type(s) == 'String')
        lines.append(f"  '{k}': [{names}],")
lines += ['};', '',
          '// Compile-time completeness: implements every member of the',
          '// generated AppLocalizations.',
          '// ignore: unused_element',
          'class _Exhaustive implements AppLocalizations {',
          '  @override',
          "  String get localeName => 'en';"]
for k in keys:
    ps = params(k)
    lines.append('  @override')
    if ps:
        sig = ', '.join(f'{dart_type(s)} {n}' for n, s in ps)
        lines.append(f"  String {k}({sig}) => '';")
    else:
        lines.append(f"  String get {k} => '';")
lines += ['}', '']
out = root / 'test/l10n/all_messages.g.dart'
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text('\n'.join(lines), encoding='utf-8')
print(f'{out.relative_to(root)}: {len(keys)} messages')
